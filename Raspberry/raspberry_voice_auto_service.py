#!/usr/bin/env python3
"""
Apex Rover Raspberry Voice + Auto Camera Scan Service - CLEAN VERSION

Responsibilities:
  1) Listen to ESP32 command mirrors on UDP port 5055.
  2) Speak robot commands using espeak-ng.
  3) Play idle music when no command is arriving.
  4) Apply ONLY system mode commands on Raspberry:
       SYS:MODE:AUTO
         - speak it,
         - notify main_startup.py to switch Raspberry camera service to AUTO,
         - start organized camera stand scan,
         - send AUTO:FULL_SCENARIO to ESP32.
       SYS:MODE:MANUAL
         - speak it,
         - stop organized camera stand scan,
         - notify main_startup.py to switch Raspberry camera service to MANUAL.

Normal commands are voice-only on Raspberry.
Raspberry does NOT read Mega USB Serial anymore.

Music:
  Put your music file beside this script.
  Default name: idle_music.mp3

Install:
  sudo apt update
  sudo apt install -y espeak-ng mpg123 ffmpeg

Run manually:
  python3 raspberry_voice_auto_service.py

main_startup.py should start this file automatically.
"""

from __future__ import annotations

import json
import os
import signal
import socket
import subprocess
import threading
import time
import urllib.parse
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Optional


# ============================================================
# Configuration
# ============================================================

ESP32_IP = os.environ.get("APEX_ESP32_IP", "192.168.4.1")
ESP32_HTTP_PORT = int(os.environ.get("APEX_ESP32_HTTP_PORT", "80"))

UDP_LISTEN_IP = "0.0.0.0"
UDP_LISTEN_PORT = int(os.environ.get("APEX_RPI_UDP_PORT", "5055"))

BASE_DIR = Path(__file__).resolve().parent
IDLE_MUSIC_FILE = BASE_DIR / os.environ.get("APEX_IDLE_MUSIC", "idle_music.mp3")
IDLE_MUSIC_DELAY_SEC = float(os.environ.get("APEX_IDLE_MUSIC_DELAY", "4.0"))

# main_startup.py local endpoint. It starts/stops camera services.
RPI_MODE_URL = os.environ.get("APEX_RPI_MODE_URL", "http://127.0.0.1:5050/internal/mode_from_voice")

TTS_BINARIES = ["espeak-ng", "espeak"]
TTS_VOICE = os.environ.get("APEX_TTS_VOICE", "en-us")
TTS_SPEED = os.environ.get("APEX_TTS_SPEED", "150")

# Auto camera scan pattern.
# Servo angles must stay inside 0..90.
AUTO_SCAN_ENABLED = True
AUTO_SCAN_SERVO_ANGLES = [0, 45, 90]
AUTO_SCAN_STEP_LEFT = 100
AUTO_SCAN_STEP_RIGHT = 150
AUTO_SCAN_RETURN_LEFT = 50
AUTO_SCAN_DELAY_SEC = 0.75
AUTO_SCAN_CYCLE_PAUSE_SEC = 0.35

SEND_FULL_SCENARIO_ON_AUTO = True
FULL_SCENARIO_DELAY_SEC = 0.8

# Same command may arrive twice because ESP32 mirrors IN and OUT.
DUPLICATE_COMMAND_WINDOW_SEC = 1.2
SYSTEM_MODE_DUPLICATE_WINDOW_SEC = 4.0

# Commands generated by this Raspberry service should not be spoken again
# when ESP32 mirrors them back.
SELF_SENT_IGNORE_WINDOW_SEC = 3.0

_stop_event = threading.Event()
_print_lock = threading.Lock()


def log(message: str) -> None:
    with _print_lock:
        print(message, flush=True)


def find_binary(names: list[str]) -> Optional[str]:
    for name in names:
        try:
            result = subprocess.run(
                ["which", name],
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                text=True,
                check=False,
            )
            path = result.stdout.strip()
            if path:
                return path
        except Exception:
            pass
    return None


# ============================================================
# Self-sent command silence tracker
# ============================================================

class SelfSentSilencer:
    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._items: dict[str, float] = {}

    def add(self, command: str) -> None:
        command = command.strip().upper()
        if not command:
            return
        with self._lock:
            self._items[command] = time.time()

    def should_ignore(self, command: str) -> bool:
        command = command.strip().upper()
        now = time.time()
        with self._lock:
            expired = [cmd for cmd, ts in self._items.items() if now - ts > SELF_SENT_IGNORE_WINDOW_SEC]
            for cmd in expired:
                self._items.pop(cmd, None)

            ts = self._items.get(command)
            if ts is None:
                return False
            if now - ts <= SELF_SENT_IGNORE_WINDOW_SEC:
                return True
            self._items.pop(command, None)
            return False


self_sent = SelfSentSilencer()


# ============================================================
# ESP32 / local mode command helpers
# ============================================================

def esp32_command_url(command: str) -> str:
    encoded = urllib.parse.quote(command, safe="")
    return f"http://{ESP32_IP}:{ESP32_HTTP_PORT}/command?cmd={encoded}"


def send_command_to_esp32(command: str, timeout: float = 1.5, silent_when_mirrored: bool = True) -> bool:
    if silent_when_mirrored:
        self_sent.add(command)

    url = esp32_command_url(command)
    try:
        with urllib.request.urlopen(url, timeout=timeout) as response:
            body = response.read(160).decode("utf-8", errors="ignore")
            ok = 200 <= response.status < 300
            log(f"[RPI -> ESP32] {command} HTTP {response.status} {body[:90]}")
            return ok
    except Exception as exc:
        log(f"[RPI -> ESP32 ERROR] {command}: {exc}")
        return False


def notify_mode_manager(mode: str) -> bool:
    mode = mode.upper().strip()
    url = RPI_MODE_URL + "?mode=" + urllib.parse.quote(mode, safe="")
    try:
        with urllib.request.urlopen(url, timeout=1.5) as response:
            body = response.read(160).decode("utf-8", errors="ignore")
            ok = 200 <= response.status < 300
            log(f"[VOICE -> MAIN] mode={mode} HTTP {response.status} {body[:90]}")
            return ok
    except Exception as exc:
        log(f"[VOICE -> MAIN ERROR] mode={mode}: {exc}")
        return False


